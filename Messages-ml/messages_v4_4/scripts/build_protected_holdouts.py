def save_suite(filename, records, suite_name):
    path = HOLDOUT_DIR / filename
    with open(path, "w", encoding="utf-8") as f:
        for idx, r in enumerate(records):
            item = {
                "message_id": f"{suite_name}_{idx+1:04d}",
                "raw_text": r["raw_text"],
                "security_label": r["security_label"],
                "category": r["category"],
                "source_id": f"V4_4_HOLDOUT_{suite_name.upper()}",
                "source_type": "PROTECTED_HOLDOUT"
            }
            f.write(json.dumps(item, ensure_ascii=False) + "\n")
    print(f"Saved {len(records)} records to {path}")

